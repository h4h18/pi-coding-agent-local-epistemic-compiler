export function architecturalDisposition(state: RunState): ArchitecturalDisposition {
  return DISPOSITION_BY_STATE[state];
}

export function isArchitecturalReady(state: RunState): boolean {
  return DISPOSITION_BY_STATE[state] === "READY";
}

export function classifiedRunStates(): typeof DISPOSITION_BY_STATE {
  if (Object.keys(DISPOSITION_BY_STATE).length !== RUN_STATES.length) {
    throw new Error("disposition map drifted from RUN_STATES");
  }
  return DISPOSITION_BY_STATE;
}
