export type DigestProjectionEntry = (typeof DIGEST_PROJECTION_REGISTRY)[number];
export type RegisteredDigestDomain = DigestProjectionEntry["domain"];

const DOMAIN_SET: ReadonlySet<string> = new Set(
  DIGEST_PROJECTION_REGISTRY.map((entry) => entry.domain),
);

export function isDigestDomain(value: string): value is RegisteredDigestDomain {
  return DOMAIN_SET.has(value);
}
